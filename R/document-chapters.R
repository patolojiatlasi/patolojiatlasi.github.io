# Shared selection rules for document YAMLs and the files render_format creates.
# Unknown chapters and unexplained omissions are errors, never implicit filtering.
document_chapter_plan <- function(language, format, mapping_file = "chapter-mappings.yml") {
  stopifnot(language %in% c("TR", "EN"), format %in% c("pdf", "epub_word"))
  mappings <- yaml::read_yaml(mapping_file)$chapters
  lang <- tolower(language)
  target_key <- paste(lang, format, sep = "_")
  missing_target <- function(x) is.null(x) || length(x) != 1L || is.na(x) ||
    x %in% c("", ".na.character")
  copies <- list()
  omissions <- character()
  resolve <- function(href) {
    # Quarto requires the unsuffixed index.qmd as the book's home page.
    stem <- sub("\\.qmd$", "", href)
    hits <- which(vapply(mappings, function(row) {
      stem %in% c(row[[lang]], row[[paste0("document_aliases_", language)]],
                  if (row$tr == "index") "index")
    }, logical(1)))
    if (length(hits) != 1L) stop("Expected one mapping for ", language, " ", href,
                                "; found ", length(hits))
    row <- mappings[[hits]]
    target <- row[[target_key]]
    if (missing_target(target)) {
      reason <- row$document_omission
      if (is.null(reason) || !nzchar(reason)) stop("Unexplained document omission: ", href)
      omissions <<- c(omissions, setNames(reason, href))
      message("Omitting ", language, "/", format, " ", href, ": ", reason)
      return(NULL)
    }
    source <- paste0(row$tr, ".qmd")
    if (!file.exists(source)) stop("Missing chapter source: ", source, " (", href, ")")
    target <- if (stem == "index") "index.qmd" else paste0(target, ".qmd")
    copies[[length(copies) + 1L]] <<- data.frame(source = source, target = target)
    target
  }
  walk <- function(obj) {
    if (is.character(obj)) {
      return(lapply(obj, function(x) if (grepl("\\.qmd$", x)) resolve(x) else x))
    }
    if (!is.list(obj)) return(obj)
    if (!is.null(obj$href)) {
      href <- resolve(obj$href)
      if (is.null(href)) return(NULL)
      obj$href <- href
      return(obj)
    }
    if (is.null(names(obj))) {
      result <- unlist(lapply(obj, function(x) {
        if (is.character(x) && length(x) == 1L) {
          value <- if (grepl("\\.qmd$", x)) resolve(x) else x
        } else value <- walk(x)
        if (is.null(value)) list() else list(value)
      }), recursive = FALSE)
      return(result)
    }
    for (key in intersect(c("book", "chapters", "appendices"), names(obj))) {
      obj[[key]] <- walk(obj[[key]])
    }
    # Do not leave empty book parts after an explicit exclusion.
    if (!is.null(obj$part) && "chapters" %in% names(obj) && !length(obj$chapters)) return(NULL)
    obj
  }
  config <- walk(yaml::read_yaml(paste0("_quarto_chapters_", language, ".yml")))
  copies <- do.call(rbind, copies)
  if (anyDuplicated(copies$target)) stop("Duplicate document chapter targets")
  list(config = config, copies = copies, omissions = omissions)
}

write_document_chapters <- function(plan, language, format) {
  output <- paste0("_quarto_chapters_", language, "_", format, ".yml")
  writeLines(c("# AUTO-GENERATED by R/generate-chapter-yamls.R; do not edit.",
               yaml::as.yaml(plan$config)), output)
  invisible(output)
}
